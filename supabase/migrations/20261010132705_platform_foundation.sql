create schema if not exists private;

create or replace function private.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  avatar_url text,
  phone text,
  state text,
  district text,
  preferred_language text not null default 'en',
  role text not null default 'farmer' check (role in ('farmer', 'buyer', 'expert', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, avatar_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', ''),
    coalesce(new.raw_user_meta_data ->> 'avatar_url', new.raw_user_meta_data ->> 'picture')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

revoke all on function private.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

create table public.farms (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 120),
  state text not null,
  district text not null,
  village text,
  acreage numeric(10,2) check (acreage > 0),
  soil_type text,
  irrigation_type text,
  current_crop text,
  sowing_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.listings (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  seller_name text not null,
  title text not null check (char_length(title) between 3 and 140),
  crop text not null check (char_length(crop) between 2 and 80),
  variety text,
  description text not null default '' check (char_length(description) <= 3000),
  quantity numeric(12,2) not null check (quantity > 0),
  unit text not null check (unit in ('kg', 'quintal', 'tonne', 'piece', 'crate')),
  price numeric(12,2) not null check (price >= 0),
  state text not null,
  district text not null,
  harvest_date date,
  contact_phone text,
  image_paths text[] not null default '{}',
  status text not null default 'active' check (status in ('draft', 'active', 'reserved', 'sold', 'expired')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.diagnoses (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  farm_id uuid references public.farms(id) on delete set null,
  analysis_mode text not null check (analysis_mode in ('disease_diagnosis', 'crop_identification', 'field_health_analysis')),
  image_path text not null,
  crop text,
  condition text,
  confidence numeric(4,3) check (confidence between 0 and 1),
  severity text check (severity in ('unknown', 'low', 'medium', 'high', 'critical')),
  result jsonb not null,
  source text not null default 'web' check (source in ('web', 'telegram')),
  created_at timestamptz not null default now()
);

create table public.news_articles (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  summary text not null default '',
  source_name text not null,
  source_url text not null unique,
  image_url text,
  category text not null default 'general',
  state text,
  crop text,
  published_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table public.telegram_link_tokens (
  token text primary key,
  user_id uuid not null unique references public.profiles(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table public.telegram_accounts (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  chat_id bigint not null unique,
  username text,
  linked_at timestamptz not null default now()
);

create table public.telegram_updates (
  update_id bigint primary key,
  received_at timestamptz not null default now()
);

create table public.commodity_prices (
  id bigint generated by default as identity primary key,
  date date not null,
  state text not null,
  district text not null,
  commodity text not null,
  min_price numeric not null,
  max_price numeric not null,
  price numeric not null,
  month integer not null,
  year integer not null,
  unique (date, state, district, commodity, min_price, max_price)
);

